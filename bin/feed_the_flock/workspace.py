def database_signature() -> tuple[tuple[int, int, int] | None, ...]:
    """Observe SQLite changes without holding its replaceable WAL sidecar open."""
    signature: list[tuple[int, int, int] | None] = []
    for path in (DB_PATH, Path(f"{DB_PATH}-wal")):
        try:
            stat = path.stat()
            signature.append((stat.st_ino, stat.st_size, stat.st_mtime_ns))
        except FileNotFoundError:
            signature.append(None)
    return tuple(signature)


@dataclass
class ImportedNote:
    text: str
    sent: bool


@dataclass
class ImportedSection:
    name: str
    notes: list[ImportedNote]
    implicit: bool = False


def bucket_markdown_text(db: sqlite3.Connection, bucket_id: str) -> tuple[str, str]:
    bucket = db.execute("SELECT name FROM buckets WHERE id = ?", (bucket_id,)).fetchone()
    if not bucket:
        raise ValueError("bucket does not exist")
    lines = [f"# {bucket['name']}", "", "<!-- Generated by Feed the Flock. -->", ""]
    sections = db.execute(
        "SELECT id, name FROM sections WHERE bucket_id = ? ORDER BY position, name",
        (bucket_id,),
    ).fetchall()
    for section in sections:
        notes = db.execute(
            "SELECT n.text, q.delivered_at IS NOT NULL AS sent FROM notes n "
            "LEFT JOIN feed_queue q ON q.note_id = n.id "
            "WHERE n.section_id = ? ORDER BY n.position, n.created_at",
            (section["id"],),
        ).fetchall()
        if not notes and section["name"] == "Unsorted":
            continue
        lines.extend((f"## {section['name']}", ""))
        for note in notes:
            text = str(note["text"]).replace("\n", "\n  ")
            lines.append(f"- [{'x' if note['sent'] else ' '}] {text}")
        lines.append("")
    return str(bucket["name"]), "\n".join(lines).rstrip() + "\n"


def atomic_write(path: Path, content: bytes, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, mode)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def write_bucket_export(db: sqlite3.Connection, bucket_id: str) -> Path:
    bucket_name, markdown = bucket_markdown_text(db, bucket_id)
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)
    file_stem = re.sub(r"[^A-Za-z0-9._-]+", "-", bucket_name).strip("-") or "bucket"
    path = EXPORT_DIR / f"{file_stem}.md"
    atomic_write(path, markdown.encode("utf-8"))
    return path


def render_bucket_markdown(db: sqlite3.Connection, bucket_id: str) -> Path:
    _, markdown = bucket_markdown_text(db, bucket_id)
    export_dir = STATE_DIR / "buckets"
    export_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    path = export_dir / f"{bucket_id}.md"
    atomic_write(path, markdown.encode("utf-8"))
    return path


def parse_bucket_markdown(markdown: str) -> tuple[str, list[ImportedSection]]:
    if not markdown.strip():
        raise ValueError("Markdown file is empty")
    if len(markdown.encode("utf-8")) > 2 * 1024 * 1024:
        raise ValueError("Markdown imports must be at most 2 MB")
    bucket_name = ""
    sections: list[ImportedSection] = []
    current_section: ImportedSection | None = None
    current_note: ImportedNote | None = None
    for line_number, raw_line in enumerate(markdown.lstrip("\ufeff").splitlines(), 1):
        heading = re.fullmatch(r"(#{1,2})\s+(.+?)(?:\s+#+)?\s*", raw_line)
        if heading:
            level, name = len(heading.group(1)), " ".join(heading.group(2).split())
            current_note = None
            if level == 1:
                if bucket_name:
                    raise ValueError(f"line {line_number}: only one bucket heading is allowed")
                if not name or len(name) > 40:
                    raise ValueError("bucket title must be between 1 and 40 characters")
                bucket_name = name
            else:
                if not bucket_name:
                    raise ValueError(f"line {line_number}: section appears before bucket title")
                if not name or len(name) > 50:
                    raise ValueError(f"line {line_number}: section title must be at most 50 characters")
                if any(section.name.casefold() == name.casefold() for section in sections):
                    raise ValueError(f"line {line_number}: duplicate section title: {name}")
                current_section = ImportedSection(name, [])
                sections.append(current_section)
            continue
        continuation = re.fullmatch(r"(?: {2}|\t)(.*)", raw_line)
        if continuation and current_note is not None:
            current_note.text += "\n" + continuation.group(1)
            continue
        task = re.fullmatch(r"\s*[-*+]\s+(?:\[([ xX])\]\s+)?(.*)", raw_line)
        if task:
            if not bucket_name:
                raise ValueError(f"line {line_number}: note appears before bucket title")
            if current_section is None:
                current_section = ImportedSection("Unsorted", [], implicit=True)
                sections.append(current_section)
            text = task.group(2).strip()
            if not text:
                raise ValueError(f"line {line_number}: note text cannot be empty")
            current_note = ImportedNote(text, bool(task.group(1) and task.group(1).lower() == "x"))
            current_section.notes.append(current_note)
            continue
        stripped = raw_line.strip()
        if not stripped or (stripped.startswith("<!--") and stripped.endswith("-->")):
            continue
        raise ValueError(f"line {line_number}: expected a bucket heading, section heading, or list item")
    if not bucket_name:
        raise ValueError("Markdown file must contain one # bucket title")
    return bucket_name, sections


def import_bucket_markdown(db: sqlite3.Connection, markdown: str) -> tuple[str, int]:
    bucket_name, sections = parse_bucket_markdown(markdown)
    if len(sections) > 200:
        raise ValueError("Markdown imports support at most 200 sections")
    if sum(len(section.notes) for section in sections) > 2000:
        raise ValueError("Markdown imports support at most 2,000 notes")
    if db.execute("SELECT COUNT(*) FROM buckets").fetchone()[0] >= 100:
        raise ValueError("at most 100 buckets are supported")
    if db.execute("SELECT 1 FROM buckets WHERE name = ? COLLATE NOCASE", (bucket_name,)).fetchone():
        raise ValueError(f"bucket already exists: {bucket_name}")
    stem = re.sub(r"[^a-z0-9]+", "-", bucket_name.lower()).strip("-") or "bucket"
    bucket_id, suffix = stem, 2
    while db.execute("SELECT 1 FROM buckets WHERE id = ?", (bucket_id,)).fetchone():
        bucket_id, suffix = f"{stem}-{suffix}", suffix + 1
    position = db.execute("SELECT COALESCE(MAX(position), -1) + 1 FROM buckets").fetchone()[0]
    db.execute("INSERT INTO buckets(id, name, position) VALUES (?, ?, ?)", (bucket_id, bucket_name, position))
    fallback_id = ensure_unsorted_section(db, bucket_id)
    section_ids: list[str] = []
    if sections and not sections[0].implicit:
        db.execute("UPDATE sections SET name = ? WHERE id = ?", (sections[0].name, fallback_id))
        section_ids.append(fallback_id)
        remaining_sections = sections[1:]
    else:
        if sections:
            section_ids.append(fallback_id)
        remaining_sections = sections[1:] if sections else []
    for section in remaining_sections:
        section_stem = re.sub(r"[^a-z0-9]+", "-", section.name.lower()).strip("-") or "section"
        section_id, section_suffix = f"{bucket_id}:{section_stem}", 2
        while db.execute("SELECT 1 FROM sections WHERE id = ?", (section_id,)).fetchone():
            section_id, section_suffix = f"{bucket_id}:{section_stem}-{section_suffix}", section_suffix + 1
        section_position = db.execute(
            "SELECT COALESCE(MAX(position), -1) + 1 FROM sections WHERE bucket_id = ?", (bucket_id,)
        ).fetchone()[0]
        db.execute(
            "INSERT INTO sections(id, bucket_id, name, position) VALUES (?, ?, ?, ?)",
            (section_id, bucket_id, section.name, section_position),
        )
        section_ids.append(section_id)
    delivery_sequence = db.execute(
        "SELECT COALESCE(MAX(delivery_sequence), 0) FROM feed_queue"
    ).fetchone()[0]
    note_count = 0
    for section, section_id in zip(sections, section_ids, strict=True):
        for note in section.notes:
            note_id = add_note_to_db(db, bucket_id, note.text, section_id)
            note_count += 1
            if note.sent:
                delivery_sequence += 1
                db.execute(
                    "UPDATE feed_queue SET delivered_at = ?, delivery_kind = 'import', "
                    "delivery_sequence = ? WHERE note_id = ?",
                    (int(time.time()), delivery_sequence, note_id),
                )
    set_setting(db, "active_bucket", bucket_id)
    if section_ids:
        set_setting(db, f"active_section:{bucket_id}", section_ids[0])
    return bucket_id, note_count


