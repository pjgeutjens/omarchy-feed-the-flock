def omarchy_theme() -> dict[str, str]:
    try:
        slug = read_regular_file(
            OMARCHY_THEME_NAME, root=OMARCHY_THEME_NAME.parent, max_bytes=1024,
        ).decode("utf-8").strip()
    except OSError:
        slug = ""
    if not re.fullmatch(r"[A-Za-z0-9._-]+", slug):
        slug = ""
    colors: dict[str, str] = {}
    for path in (
        OMARCHY_SYSTEM_THEMES / slug / "colors.toml",
        OMARCHY_USER_THEMES / slug / "colors.toml",
    ):
        try:
            values = tomllib.loads(
                read_regular_file(path, root=path.parent, max_bytes=64 * 1024).decode("utf-8")
            )
        except (OSError, tomllib.TOMLDecodeError):
            continue
        for key, value in values.items():
            if isinstance(value, str) and re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                colors[key] = value
    return {
        "name": slug or "unknown",
        "background": colors.get("background", "#111318"),
        "foreground": colors.get("foreground", "#e7e9ee"),
        "accent": colors.get("accent", colors.get("color4", "#8fa9ff")),
        "muted": colors.get("color8", "#858b98"),
        "border": colors.get("color8", "#292d36"),
        "error": colors.get("color1", "#ff8d91"),
        "toast": colors.get("color11", colors.get("selection_background", "#f5e6a8")),
        "toastText": colors.get("background", "#342e16"),
    }


IMAGE_TYPES = {
    "image/png": ".png",
    "image/jpeg": ".jpg",
    "image/webp": ".webp",
    "image/gif": ".gif",
}
MAX_ATTACHMENT_BYTES = 8 * 1024 * 1024
MAX_IMAGE_DIMENSION = 8192
MAX_IMAGE_PIXELS = 40_000_000


def image_dimensions(body: bytes, mime_type: str) -> tuple[int, int]:
    width = height = 0
    if mime_type == "image/png" and body.startswith(b"\x89PNG\r\n\x1a\n") and len(body) >= 24:
        width, height = int.from_bytes(body[16:20], "big"), int.from_bytes(body[20:24], "big")
    elif mime_type == "image/gif" and body[:6] in {b"GIF87a", b"GIF89a"} and len(body) >= 10:
        width, height = int.from_bytes(body[6:8], "little"), int.from_bytes(body[8:10], "little")
    elif mime_type == "image/jpeg" and body.startswith(b"\xff\xd8"):
        offset = 2
        sof_markers = set(range(0xC0, 0xC4)) | set(range(0xC5, 0xC8)) | set(range(0xC9, 0xCC)) | set(range(0xCD, 0xD0))
        while offset + 4 <= len(body):
            if body[offset] != 0xFF:
                offset += 1
                continue
            marker = body[offset + 1]
            offset += 2
            if marker in {0xD8, 0xD9} or 0xD0 <= marker <= 0xD7:
                continue
            length = int.from_bytes(body[offset:offset + 2], "big")
            if length < 2 or offset + length > len(body):
                break
            if marker in sof_markers and length >= 7:
                height = int.from_bytes(body[offset + 3:offset + 5], "big")
                width = int.from_bytes(body[offset + 5:offset + 7], "big")
                break
            offset += length
    elif mime_type == "image/webp" and body.startswith(b"RIFF") and body[8:12] == b"WEBP":
        chunk = body[12:16]
        if chunk == b"VP8X" and len(body) >= 30:
            width = 1 + int.from_bytes(body[24:27], "little")
            height = 1 + int.from_bytes(body[27:30], "little")
        elif chunk == b"VP8 " and len(body) >= 30 and body[23:26] == b"\x9d\x01\x2a":
            width = int.from_bytes(body[26:28], "little") & 0x3FFF
            height = int.from_bytes(body[28:30], "little") & 0x3FFF
        elif chunk == b"VP8L" and len(body) >= 25 and body[20] == 0x2F:
            packed = int.from_bytes(body[21:25], "little")
            width, height = 1 + (packed & 0x3FFF), 1 + ((packed >> 14) & 0x3FFF)
    if width <= 0 or height <= 0:
        raise ValueError("image data does not match its declared type")
    if width > MAX_IMAGE_DIMENSION or height > MAX_IMAGE_DIMENSION or width * height > MAX_IMAGE_PIXELS:
        raise ValueError("image dimensions exceed the 40 megapixel safety limit")
    return width, height


def note_attachments(db: sqlite3.Connection, note_id: str) -> list[dict[str, object]]:
    return [
        {
            "id": row["id"],
            "name": row["file_name"],
            "mimeType": row["mime_type"],
            "url": f"/api/attachment?id={urllib.parse.quote(row['id'])}",
        }
        for row in db.execute(
            "SELECT id, file_name, mime_type FROM attachments "
            "WHERE note_id = ? ORDER BY position, created_at",
            (note_id,),
        )
    ]


def attachment_file(db: sqlite3.Connection, attachment_id: str) -> tuple[Path, str, str]:
    row = db.execute(
        "SELECT file_path, mime_type, file_name FROM attachments WHERE id = ?",
        (attachment_id,),
    ).fetchone()
    if not row:
        raise ValueError("attachment no longer exists")
    root = Path(os.path.abspath(ATTACHMENT_DIR))
    if root.resolve() != root:
        raise ValueError("attachment directory is unsafe")
    path = Path(os.path.abspath(Path(row["file_path"])))
    if path.parent != root or not re.fullmatch(r"[0-9a-f]{32}\.(?:png|jpe?g|webp|gif)", path.name):
        raise ValueError("attachment file path is unsafe")
    return path, str(row["mime_type"]), str(row["file_name"])


def bucket_document(db: sqlite3.Connection, bucket_id: str) -> dict[str, object]:
    bucket = db.execute("SELECT id, name FROM buckets WHERE id = ?", (bucket_id,)).fetchone()
    if not bucket:
        raise ValueError("bucket does not exist")
    feed_bucket_id, feed_section_id = feed_destination(db)
    feed_row = db.execute(
        "SELECT s.name, b.name AS bucket_name FROM sections s "
        "JOIN buckets b ON b.id = s.bucket_id WHERE s.id = ?", (feed_section_id,)
    ).fetchone()
    queue_rows = feed_section_queue(db)
    queue_positions = {
        row["section_id"]: position for position, row in enumerate(queue_rows)
    }
    feed_queue = [
        {
            "sectionId": row["section_id"], "sectionName": row["name"],
            "bucketId": row["bucket_id"], "bucketName": row["bucket_name"],
            "position": position,
        }
        for position, row in enumerate(queue_rows)
    ]
    next_feed_bucket_id = queue_rows[0]["bucket_id"] if queue_rows else ""
    next_feed_section_id = queue_rows[0]["section_id"] if queue_rows else ""
    next_feed_row = queue_rows[0] if queue_rows else None
    feed_enabled = setting(db, "feed_enabled", "0") == "1"
    delivery_mode = setting(db, "delivery_mode", "idle-active-next")
    queue_order = setting(db, "queue_order", "fifo")
    try:
        stored_active_notes = json.loads(setting(db, "active_delivery_notes", "[]"))
        active_note_ids = (
            {str(note_id) for note_id in stored_active_notes}
            if isinstance(stored_active_notes, list) else set()
        )
    except json.JSONDecodeError:
        active_note_ids = set()
    mode_label = {
        "idle-active-next": "Active section · One by one",
        "idle-active-batch": "Active section · Batch",
        "idle-all-next": "All sections · One by one",
        "idle-all-batch": "All sections · Batch",
    }.get(delivery_mode, delivery_mode)
    feed_label = f"Feeding · {mode_label} · {queue_order.upper()}"
    note_order = "DESC" if queue_order == "lifo" else "ASC"
    sections = []
    note_count = 0
    submitted_count = 0
    section_rows = db.execute(
        "SELECT id, name, system_kind, position FROM sections "
        "WHERE bucket_id = ? ORDER BY position, name", (bucket_id,)
    ).fetchall()
    for section in section_rows:
        notes = [
            {
                "id": row["id"], "text": row["text"], "sent": bool(row["sent"]),
                "active": str(row["id"]) in active_note_ids,
                "jumpedQueue": bool(row["jumped_queue"]),
                "deliveredAt": row["delivered_at"],
                "deliverySequence": row["delivery_sequence"],
                "deliveryError": row["delivery_error"],
            }
            for row in db.execute(
                "SELECT n.id, n.text, q.delivered_at, q.delivery_sequence, q.error AS delivery_error, "
                "q.delivered_at IS NOT NULL AS sent, "
                "(q.delivery_kind = 'feed_now' AND q.delivered_at IS NOT NULL) AS jumped_queue "
                "FROM notes n LEFT JOIN feed_queue q ON q.note_id = n.id "
                "WHERE n.section_id = ? "
                "ORDER BY CASE WHEN q.delivered_at IS NOT NULL THEN 0 ELSE 1 END, "
                "CASE WHEN q.delivered_at IS NOT NULL THEN q.delivery_sequence END ASC, "
                f"CASE WHEN q.delivered_at IS NULL THEN n.position END {note_order}, "
                f"n.created_at {note_order}",
                (section["id"],),
            )
        ]
        for note in notes:
            note["attachments"] = note_attachments(db, str(note["id"]))
        note_count += len(notes)
        submitted_count += sum(1 for note in notes if note["sent"])
        sections.append({
            "id": section["id"], "name": section["name"],
            "systemKind": section["system_kind"], "notes": notes,
            "feedCurrent": section["id"] == feed_section_id and feed_enabled,
            "feedNext": section["id"] == next_feed_section_id,
            "feedActive": section["id"] == feed_section_id and feed_enabled,
            "feedQueuePosition": queue_positions.get(section["id"], -1),
            "feedLabel": feed_label if section["id"] == feed_section_id and feed_enabled else (
                f"Queued · position {queue_positions[section['id']] + 1}"
                if section["id"] in queue_positions else ""
            ),
        })
    return {
        "id": bucket["id"], "name": bucket["name"], "sections": sections,
        "noteCount": note_count, "submittedCount": submitted_count,
        "queuedCount": note_count - submitted_count, "feedBucketId": feed_bucket_id,
        "feedSectionId": feed_section_id,
        "feedEnabled": feed_enabled, "deliveryMode": delivery_mode,
        "queueOrder": queue_order, "activeNoteIds": sorted(active_note_ids),
        "feedBucketName": feed_row["bucket_name"],
        "feedSectionName": feed_row["name"],
        "nextFeedBucketId": next_feed_bucket_id, "nextFeedSectionId": next_feed_section_id,
        "nextFeedBucketName": next_feed_row["bucket_name"] if next_feed_row else "",
        "nextFeedSectionName": next_feed_row["name"] if next_feed_row else "",
        "feedQueue": feed_queue,
    }


def place_note_in_section(
    db: sqlite3.Connection, note_id: str, section_id: str, before_note_id: str | None
) -> None:
    note = db.execute(
        "SELECT n.bucket_id, n.section_id, q.delivered_at "
        "FROM notes n LEFT JOIN feed_queue q ON q.note_id = n.id WHERE n.id = ?",
        (note_id,),
    ).fetchone()
    section = db.execute("SELECT bucket_id FROM sections WHERE id = ?", (section_id,)).fetchone()
    if not note:
        raise ValueError("note no longer exists")
    if note["delivered_at"] is not None:
        raise ValueError("submitted notes retain delivery order; requeue the note before moving it")
    if not section or section["bucket_id"] != note["bucket_id"]:
        raise ValueError("target section does not exist")
    if before_note_id == note_id:
        return
    if before_note_id:
        target = db.execute(
            "SELECT n.section_id, q.delivered_at FROM notes n "
            "LEFT JOIN feed_queue q ON q.note_id = n.id WHERE n.id = ?",
            (before_note_id,),
        ).fetchone()
        if not target or target["section_id"] != section_id:
            raise ValueError("target note does not exist in that section")
        if target["delivered_at"] is not None:
            raise ValueError("pending notes cannot be placed inside submitted history")

    source_section_id = note["section_id"]
    source_ids = [
        row[0] for row in db.execute(
            "SELECT id FROM notes WHERE section_id = ? AND id != ? ORDER BY position, created_at",
            (source_section_id, note_id),
        )
    ]
    if source_section_id == section_id:
        target_ids = source_ids
    else:
        target_ids = [
            row[0] for row in db.execute(
                "SELECT id FROM notes WHERE section_id = ? ORDER BY position, created_at",
                (section_id,),
            )
        ]
    display_ids = list(reversed(target_ids)) if setting(db, "queue_order", "fifo") == "lifo" else target_ids
    insertion = display_ids.index(before_note_id) if before_note_id else len(display_ids)
